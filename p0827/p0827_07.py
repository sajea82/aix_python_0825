# 리스트 = 배열
a = 1
arr = [1,2,3,4,5]
print(type(a))   # int
print(a)         # 1
print(a+1)       # 2
print(type(arr)) # list
print(arr)       # [1,2,3,4,5]
print(arr[4]+1) 
print(arr[2])
print(len(arr)) # 리스트 개수 length줄임.

# 리스트는 []시작
# 리스트는 여러개를 저장
# 리스트는 0부터 주소가 시작
# 리스트를 print하면 모두 출력가능
# 리스트의 특정주소로 그 값을 출력할수 있음.
# 리스트 개수 :len()
# 리스트 안에는 모든 타입을 넣을수 있음 
